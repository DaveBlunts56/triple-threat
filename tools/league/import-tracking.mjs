// Converts the owner's private match list and NBA tracking totals into a name-free game module.
// Usage: node tools/league/import-tracking.mjs matched.csv data-folder
// The folder contains tracking_SEASON.csv, pt_shot_defender_SEASON.csv and shot_zones_SEASON.csv.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readCsv } from './import.mjs';
import { LEAGUE } from '../../src/sim/league.js';

const [mapping, folder] = process.argv.slice(2);
const read = path => readCsv(readFileSync(path, 'utf8'));
const normalized = name => name.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]/g, '');
const round = number => Number(number.toFixed(4));
const seasons = ['2025-26', '2024-25', '2026-27'];
const regular = (file, season) => read(join(folder, file + '_' + season + '.csv')).filter(row => row.SEASON_TYPE === 'Regular Season');
const playerId = row => Number(row.PLAYER_ID);

const sources = seasons.map(season => {
  const drives = regular('tracking', season).filter(row => row.PT_MEASURE_TYPE === 'Drives' && row.PLAYER_OR_TEAM === 'Player' && Number(row.MIN) > 0);
  const zones = new Map(regular('shot_zones', season).map(row => [playerId(row), row]));
  const shots = new Map();
  for (const row of regular('pt_shot_defender', season)) {
    const profile = shots.get(playerId(row)) ?? { total: 0, threes: 0 };
    profile.total += Number(row.FGA);
    profile.threes += Number(row.FG3A);
    shots.set(playerId(row), profile);
  }
  return { season, drives, zones, shots };
});

const byPlayer = new Map(read(mapping).map(row => [row.team_id + '/' + row.jersey_number, row]));
// An abbreviated name in the match list does not match the official spelling.
const aliases = { "DET/5": 1641842 };
const counts = {};
const rows = [];
for (const club of LEAGUE) for (const player of club.players) {
  const key = club.key + '/' + player.number, match = byPlayer.get(key);
  if (match?.player_name !== player.name) throw new Error('Missing or mismatched mapping for ' + key);
  const name = normalized(match.nba_player_equivalent);
  const matches = row => normalized(row.PLAYER_NAME.replace(/ (Jr\.?|II|III|IV)$/i, '')) === name ||
    normalized(row.PLAYER_NAME) === name || playerId(row) === aliases[key];
  const source = sources.find(s => s.drives.some(matches));
  if (!source) throw new Error('Missing tracking for ' + key);
  const d = source.drives.find(matches);
  const id = playerId(d), z = source.zones.get(id), shot = source.shots.get(id);
  const paint = Number(z?.RA_FGA) + Number(z?.PAINT_FGA), mid = Number(z?.MID_FGA);
  const three = shot?.total > 0 ? shot.threes / shot.total : 0;
  const rim = paint + mid > 0 ? (1 - three) * paint / (paint + mid) : 0;
  const attempts = shot?.total > 0 && (three === 1 || paint + mid > 0) ? shot.total : 0;
  const drive = Number(d.DRIVES), min = Number(d.MIN);
  const entry = {
    minutes: round(min / Number(d.GP)), trackedMinutes: min,
    drives36: round(drive * 36 / min), drives: drive, pass: round(Number(d.DRIVE_PASSES_PCT)),
    attempts, rim: round(rim), three: round(three),
  };
  if (!Object.values(entry).every(Number.isFinite)) throw new Error('Invalid tracking totals for ' + key);
  counts[source.season] = (counts[source.season] ?? 0) + 1;
  rows.push(`  ${JSON.stringify(key)}: ${JSON.stringify(entry)},`);
}
writeFileSync(new URL('../../src/sim/player-tracking.js', import.meta.url),
  '// Generated by tools/league/import-tracking.mjs. See docs/PLAYER-TRACKING.md.\nexport const PLAYER_TRACKING = {\n' + rows.join('\n') + '\n};\n');
console.log(counts);
